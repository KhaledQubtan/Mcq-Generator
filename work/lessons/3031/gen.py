def add(q, ch, ans=0):
    assert len(ch) == 4 and len(set(ch)) == 4, (q, ch)
    QS.append((q, ch, ans))

def addn(q, val, nums, unit="", fmt=None):
    """numeric question: nums[0] must equal computed val; others must differ"""
    assert abs(nums[0] - val) < 1e-6, (q, val, nums[0])
    for x in nums[1:]:
        assert abs(x - val) > 1e-3, (q, val, x)
    ch = [fmt(x) if fmt else num(x, unit) for x in nums]
    add(q, ch, 0)

def acc(m1, m2, G=g): return (m1 - m2) / (m1 + m2) * G
def ten(m1, m2, G=g): return 2 * m1 * m2 / (m1 + m2) * G

