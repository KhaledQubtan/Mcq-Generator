QS = []

def F(x):
    if isinstance(x, str): return x
    if abs(x - round(x)) < 1e-9: return str(int(round(x)))
    s = f"{x:.4f}".rstrip("0").rstrip(".")
    return s

def num(x, unit=""):
    return f"${F(x)}$" + (f" {unit}" if unit else "")

MS2 = "م/ث$^{2}$"; CMS2 = "سم/ث$^{2}$"; MS = "م/ث"; CMS = "سم/ث"
